def extract_differentiable_features(img_tensor, device="cuda"):
    """
    Expects input shape: [1, 1, H, W], values normalized between 0.0 and 255.0.
    Gradients flow back uninterruptedly through all features.
    """
    img = img_tensor.to(device).float()
    _, _, H, W = img.shape
    total_pixels = H * W
    k = 0.5 # Sigmoid sharpness for soft thresholds
    
    # 1. Soft Thresholding Masks
    mask_low = torch.sigmoid((100.0 - img) * k)
    mask_high = torch.sigmoid((50.0 - img) * k)

    # 2. Area & Edge Features
    area_fraction = torch.sum(mask_low) / total_pixels
    sobel_x = torch.tensor([[-1, 0, 1], [-2, 0, 2], [-1, 0, 1]], dtype=torch.float32, device=device).view(1, 1, 3, 3)
    sobel_y = torch.tensor([[-1, -2, -1], [0, 0, 0], [1, 2, 1]], dtype=torch.float32, device=device).view(1, 1, 3, 3)
    grad_x = F.conv2d(img, sobel_x, padding=1)
    grad_y = F.conv2d(img, sobel_y, padding=1)
    edge_magnitude = torch.sqrt(grad_x**2 + grad_y**2 + 1e-8)
    soft_edges = torch.sigmoid((edge_magnitude - 30.0) * 0.2)
    edge_density = torch.sum(soft_edges) / total_pixels

    # 3. Connected Component Approximations
    num_clusters = torch.sum(mask_high) / (mask_high.sum() / (torch.sum(mask_high * img) + 1e-5) + 1.0)
    mean_cluster_area = torch.sum(mask_high) / (num_clusters + 1e-5)
    
    x_coords = torch.linspace(-1, 1, W, device=device).view(1, 1, 1, -1).expand_as(img)
    y_coords = torch.linspace(-1, 1, H, device=device).view(1, 1, -1, 1).expand_as(img)
    mu_x = torch.sum(mask_high * x_coords) / (torch.sum(mask_high) + 1e-5)
    mu_y = torch.sum(mask_high * y_coords) / (torch.sum(mask_high) + 1e-5)
    m20 = torch.sum(mask_high * (x_coords - mu_x)**2)
    m02 = torch.sum(mask_high * (y_coords - mu_y)**2)
    m11 = torch.sum(mask_high * (x_coords - mu_x) * (y_coords - mu_y))
    common_term = torch.sqrt((m20 - m02)**2 + 4 * m11**2 + 1e-8)
    mean_eccentricity = common_term / (m20 + m02 + common_term + 1e-8)

    # 4. Intensity Statistics
    eps = 1e-5
    sum_mask = torch.sum(mask_low) + eps
    mean_intensity = torch.sum(img * mask_low) / sum_mask
    variance_intensity = torch.sum(((img - mean_intensity) ** 2) * mask_low) / sum_mask
    std_intensity = torch.sqrt(variance_intensity + eps)
    skew_intensity = torch.sum(((img - mean_intensity) / std_intensity) ** 3 * mask_low) / sum_mask
    kurt_intensity = torch.sum(((img - mean_intensity) / std_intensity) ** 4 * mask_low) / sum_mask - 3.0

    # 5. Skeletonization (Soft Min Pooling)
    thinned = mask_low
    for _ in range(3):
        thinned = -F.max_pool2d(-thinned, kernel_size=3, stride=1, padding=1)
    skeleton_length = torch.sum(thinned)
    neighbor_kernel = torch.ones((1, 1, 3, 3), device=device)
    neighbor_kernel[0, 0, 1, 1] = 0.0
    neighbor_count = F.conv2d(thinned, neighbor_kernel, padding=1) * thinned
    num_endpoints = torch.sum(torch.sigmoid((1.5 - torch.abs(neighbor_count - 1.0)) * 5.0))
    num_branches = torch.sum(torch.sigmoid((neighbor_count - 2.5) * 5.0))

    # 6. Distance Transform (Soft Multi-scale Erosion)
    dist_map = torch.zeros_like(img)
    temp = mask_low
    for _ in range(1, 8):
        temp = -F.max_pool2d(-temp, kernel_size=3, stride=1, padding=1)
        dist_map += temp
    mean_thickness = torch.sum(dist_map * mask_low) / sum_mask
    max_thickness = torch.max(dist_map)

    # 7. Local Variance Texture Filter
    mean_kernel_15 = torch.ones((1, 1, 15, 15), device=device) / 225.0
    local_mean = F.conv2d(img, mean_kernel_15, padding=7)
    local_sq_mean = F.conv2d(img**2, mean_kernel_15, padding=7)
    local_std = torch.sqrt(torch.clamp(local_sq_mean - local_mean**2, min=1e-8))
    mean_local_std = torch.mean(local_std)
    std_local_std = torch.std(local_std)

    # 8. Box-Counting Fractal Dimension
    counts = []
    sizes = [2, 4, 8, 16]
    for size in sizes:
        downsampled = F.interpolate(mask_low, size=(H // size, W // size), mode='bilinear', align_corners=False)
        counts.append(torch.sum(downsampled))
    x_log = torch.tensor([math.log(s) for s in sizes], device=device)
    y_log = torch.stack([torch.log(c + 1e-5) for c in counts])
    x_mean = torch.mean(x_log)
    y_mean = torch.mean(y_log)
    slope = torch.sum((x_log - x_mean) * (y_log - y_mean)) / torch.sum((x_log - x_mean) ** 2)
    fractal_dim = -slope

    # 9. FFT Frequency Spectrum
    fft_dims = torch.fft.fft2(img.squeeze(1))
    fft_shifted = torch.fft.fftshift(fft_dims)
    fft_magnitude = torch.log(torch.abs(fft_shifted) + 1.0)
    fft_energy = torch.mean(fft_magnitude)

    # Assemble Output Tensors
    core_features = torch.stack([
        area_fraction, edge_density, num_clusters, mean_cluster_area, mean_eccentricity,
        mean_intensity, std_intensity, skew_intensity, kurt_intensity, skeleton_length,
        num_branches, num_endpoints, mean_thickness, max_thickness, 
        mean_local_std, std_local_std, fractal_dim, fft_energy
    ])
    return core_features
